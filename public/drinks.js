//   ask   其他（美式、星沁爽、果汁、Cold Foam…）→ 能否補以門市為準
//   null  熱飲、冰沙、冰淇淋飲品 → 不適用
export function refillType(d) {
  if (d.g === 'cb') return 'nocb';
  if (d.m === 'unknown') return d.t === 'iced' ? 'ask' : null; // 菜單沒寫含不含奶：不自己判斷
  if (d.t !== 'iced') return null;
  if (d.g === 'float') return null;
  if (d.g === 'ref' || d.g === 'juice' || d.coldfoam) return 'ask';
  if (hasMilk(d)) return 'milk';
  if (d.g === 'tea') return 'tea';
  return 'ask';
}

